#!/usr/bin/env python3
"""Ω11C1 — independent, read-only comparison of two Ω11B CI evidence archives.

Every PNG is SHA-checked against its own archived receipt. A high-contrast
inspection overlay is a diagnostic visualization, not changed source or proof
of a 3D visibility/depth error. No browser is executed by this auditor.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import sys
import zipfile

PIN="1482e8469b0a9e0d8cc18ea2740a01423d29ae80"
RECEIPT="captures/OMEGA11B_BROWSER_RECEIPT.json"
CASES=18


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class Evidence:
    def __init__(self, path: Path):
        self.path=path
        self.archive=zipfile.ZipFile(path, "r")
        entries=self.archive.infolist()
        names=[x.filename for x in entries]
        if len(names)!=len(set(names)):
            raise ValueError("duplicate archive paths")
        for entry in entries:
            name=PurePosixPath(entry.filename)
            if name.is_absolute() or ".." in name.parts or "\\" in entry.filename:
                raise ValueError("unsafe archive member")
            if entry.file_size>50_000_000:
                raise ValueError("unbounded evidence member")
        if RECEIPT not in names:
            raise ValueError("missing browser receipt")
        self.receipt=json.loads(self.read(RECEIPT))
        r=self.receipt
        if r.get("source_pin")!=PIN or r.get("release")!="HOLD":
            raise ValueError("source pin or release boundary changed")
        if r.get("strict_generated_byte_parity")!="FAIL":
            raise ValueError("strict generated byte-parity evidence changed")
        if r.get("observation_coverage")!="EXECUTED" or r.get("completed_cases")!=CASES:
            raise ValueError("incomplete execution evidence")
        if r.get("runtime_failures") or len(r.get("observations",[]))!=CASES:
            raise ValueError("unexpected runtime failures or case count")
        ids=[x.get("case") for x in r["observations"]]
        if len(ids)!=len(set(ids)):
            raise ValueError("duplicate observation identifier")
        self.observations={x["case"]:x for x in r["observations"]}

    def read(self, name: str) -> bytes:
        return self.archive.read(name)

    def image(self, case: str, side: str):
        from PIL import Image
        observation=self.observations[case]
        capture=observation["captures"][side]
        n=f"captures/{case}-{side}-capture.png"
        raw=self.read(n)
        if digest(raw)!=capture["capture"]:
            raise ValueError("archived screenshot SHA256 does not match receipt: "+n)
        n2=f"captures/{case}-{side}-repeat.png"
        if digest(self.read(n2))!=capture["repeat"]:
            raise ValueError("archived repeat screenshot SHA256 does not match receipt: "+n2)
        im=Image.open(io.BytesIO(raw))
        im.load()
        return im.convert("RGBA")


def compare_images(first, second, overlay: Path | None = None) -> dict:
    from PIL import Image, ImageChops
    if first.size!=second.size:
        return {"same_dimensions":False,"changed_pixels":None,
                "sizes":[list(first.size),list(second.size)]}
    diff=ImageChops.difference(first,second)
    pixels=list(diff.getdata())
    changed=[i for i,p in enumerate(pixels) if any(p)]
    if not changed:
        return {"same_dimensions":True,"changed_pixels":0,"changed_fraction":0.0,
                "max_channel_delta":0,"bbox":None}
    width,height=first.size
    xx=[i%width for i in changed]; yy=[i//width for i in changed]
    maximum=max(max(pixels[i]) for i in changed)
    if overlay:
        # Opaque diagnostic overlay: fixes the transparent-RGBA-difference trap.
        source=first.convert("RGB")
        muted=source.point(lambda c: (c*2+245)//3)
        marker=Image.new("RGB",first.size,(255,0,0))
        mask=Image.new("L",first.size,0)
        mask.putdata([255 if any(p) else 0 for p in pixels])
        result=Image.composite(marker,muted,mask)
        overlay.parent.mkdir(parents=True,exist_ok=True)
        result.save(overlay)
    return {"same_dimensions":True,"changed_pixels":len(changed),
            "changed_fraction":len(changed)/(width*height),
            "max_channel_delta":maximum,
            "bbox":[min(xx),min(yy),max(xx)+1,max(yy)+1]}


def compare_archives(a: Evidence,b: Evidence,out: Path) -> tuple[dict,int]:
    r1,r2=a.receipt,b.receipt
    for field in ("source_pin","source_hashes","config","browser_version",
                  "playwright_version","strict_generated_byte_parity","release"):
        if r1.get(field)!=r2.get(field):
            raise ValueError(f"cross-run provenance mismatch: {field}")
    if set(a.observations)!=set(b.observations):
        raise ValueError("mismatched browser case list")
    out.mkdir(parents=True,exist_ok=True)
    rows=[]
    for case in sorted(a.observations):
        o1,o2=a.observations[case],b.observations[case]
        if (o1.get("original_stable") is not True or o1.get("rebuilt_stable") is not True or
            o2.get("original_stable") is not True or o2.get("rebuilt_stable") is not True):
            raise ValueError("unstable within-run evidence: "+case)
        sides={}
        for side in ("original","rebuilt"):
            before=a.image(case,side); after=b.image(case,side)
            sides[side]=compare_images(before,after,
                    out / "overlays" / f"{case}-{side}-CROSSRUN.png")
        rows.append({"case":case,"first_classification":o1["classification"],
                     "second_classification":o2["classification"],
                     "classifications_match":o1["classification"]==o2["classification"],
                     "side_drift":sides})
    mismatches=[x for x in rows if not x["classifications_match"]]
    drift=[x for x in rows if any(y["changed_pixels"] for y in x["side_drift"].values())]
    report={"schema":"fab.visual.omega11c.crossrun.v1",
            "exact_source_pin":PIN,"run_a":str(a.path),"run_b":str(b.path),
            "first_archive_sha256":digest(a.path.read_bytes()),
            "second_archive_sha256":digest(b.path.read_bytes()),
            "browser":r1["browser_version"],"playwright":r1["playwright_version"],
            "source_hashes":r1["source_hashes"],
            "cases_checked":len(rows),"case_classification_mismatches":len(mismatches),
            "crossrun_image_drift_cases":len(drift),"observations":rows,
            "source_integrity":"PASS",
            "cross_run_pixel_reproducibility":"FAIL" if drift else "PASS_FINITE_ONLY",
            "state_readback":"NOT_RUN","depth_order_oracle":"NOT_RUN",
            "source_numeric_causation":"NOT_ESTABLISHED",
            "strict_generated_byte_parity":"FAIL",
            "scientific_admission":"NOT_RUN","host_authorization":"NOT_RUN",
            "release":"HOLD",
            "claim_boundary":"Source-matched screenshots can drift across processes with "
              "unchanged HTML. Drift cause and geometry/occlusion parity are not proven."}
    (out/"OMEGA11C_CROSSRUN_AUDIT.json").write_text(
        json.dumps(report,indent=2,sort_keys=True)+"\n",encoding="utf8")
    print(json.dumps({"checked":len(rows),"classification_mismatches":len(mismatches),
                      "image_drift_cases":len(drift),
                      "crossrun":report["cross_run_pixel_reproducibility"],
                      "release":"HOLD"}))
    return report, 0


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--first",type=Path,required=True)
    p.add_argument("--second",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    a=Evidence(args.first);b=Evidence(args.second)
    _,code=compare_archives(a,b,args.output)
    return code


if __name__=="__main__":
    sys.exit(main())
